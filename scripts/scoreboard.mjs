// Runs every test and turns the results into the public scoreboard:
// SCOREBOARD.md, docs/scoreboard.json, docs/scoreboard.svg and the table in
// README.md. A feature counts as verified only when a browser test named
// with its id passes. Nothing here is written by hand.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const features = JSON.parse(readFileSync(join(root, 'features.json'), 'utf8'));
mkdirSync(join(root, 'test-results'), { recursive: true });

function run(label, files, extraEnv = {}) {
  const out = join(root, 'test-results', `${label}.jsonl`);
  const args = ['--test', '--test-concurrency=1', `--test-reporter=${join(root, 'scripts/test-reporter.mjs')}`, `--test-reporter-destination=${out}`, ...files];
  const res = spawnSync(process.execPath, args, { cwd: root, stdio: ['ignore', 'inherit', 'inherit'], env: { ...process.env, ...extraEnv } });
  const rows = readFileSync(out, 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l));
  return { rows, code: res.status };
}

const only = process.argv.includes('--from-results');
let unit;
let e2e;
if (only) {
  const load = (n) => ({ rows: readFileSync(join(root, 'test-results', `${n}.jsonl`), 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)) });
  unit = load('unit');
  e2e = load('e2e');
} else {
  spawnSync(process.execPath, [join(root, 'scripts/build.mjs')], { cwd: root, stdio: 'inherit' });
  const list = (dir) => readdirSync(join(root, dir)).filter((f) => f.endsWith('.test.js')).sort().map((f) => join(dir, f));
  unit = run('unit', list('test/unit'));
  e2e = run('e2e', list('test/e2e'));
}

const idsIn = (name) => [...name.matchAll(/\[([A-Z]+-\d+)\]/g)].map((m) => m[1]);
const byId = new Map();
for (const r of e2e.rows) {
  for (const id of idsIn(r.name)) {
    const s = byId.get(id) || { pass: 0, fail: 0, tests: [] };
    if (r.pass) s.pass++;
    else if (!r.skipped) s.fail++;
    s.tests.push(r.name);
    byId.set(id, s);
  }
}

const areas = features.areas.map((a) => ({
  ...a,
  features: a.features.map((f) => {
    const s = byId.get(f.id);
    const status = !s ? 'todo' : s.fail ? 'failing' : s.pass ? 'verified' : 'todo';
    return { ...f, status, tests: s?.tests || [] };
  }),
}));
const all = areas.flatMap((a) => a.features);
const count = (st) => all.filter((f) => f.status === st).length;
const summary = {
  date: new Date().toISOString().slice(0, 10),
  total: all.length,
  verified: count('verified'),
  failing: count('failing'),
  todo: count('todo'),
  e2eTests: e2e.rows.length,
  e2ePassing: e2e.rows.filter((r) => r.pass).length,
  unitTests: unit.rows.length,
  unitPassing: unit.rows.filter((r) => r.pass).length,
};

const mark = { verified: '✅ verified', failing: '❌ failing', todo: '⬜ not yet' };
const md = [
  '# Placard feature scoreboard',
  '',
  `Generated by \`npm run scoreboard\` on ${summary.date}. Do not edit by hand.`,
  '',
  `**${summary.verified} of ${summary.total} features verified** by end-to-end tests in a real browser` +
    (summary.failing ? `, **${summary.failing} failing**` : '') + `, ${summary.todo} not done yet.`,
  '',
  `${summary.e2ePassing}/${summary.e2eTests} browser tests and ${summary.unitPassing}/${summary.unitTests} unit tests pass.`,
  'A feature counts as verified only when a browser test named with its id passes against the built app.',
  '',
  ...areas.flatMap((a) => [
    `## ${a.name}`,
    '',
    '| | Feature | Status |',
    '| --- | --- | --- |',
    ...a.features.map((f) => `| ${f.id} | ${f.title} | ${mark[f.status]} |`),
    '',
  ]),
].join('\n');
writeFileSync(join(root, 'SCOREBOARD.md'), md);
writeFileSync(join(root, 'docs/scoreboard.json'), JSON.stringify({ summary, areas: areas.map((a) => ({ id: a.id, name: a.name, features: a.features.map(({ id, title, status }) => ({ id, title, status })) })) }, null, 2));

// The share card.
const pct = summary.verified / summary.total;
const barW = 1040;
const card = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#16161d"/>
<rect x="0" y="0" width="1200" height="10" fill="#f25c2a"/>
<text x="80" y="130" fill="#f25c2a" font-family="Inter, Helvetica, Arial, sans-serif" font-size="34" font-weight="700" letter-spacing="4">PLACARD</text>
<text x="80" y="250" fill="#ffffff" font-family="Inter, Helvetica, Arial, sans-serif" font-size="96" font-weight="800">${summary.verified} of ${summary.total} features</text>
<text x="80" y="330" fill="#c9c9d6" font-family="Inter, Helvetica, Arial, sans-serif" font-size="44">verified by tests in a real browser</text>
<rect x="80" y="390" width="${barW}" height="28" rx="14" fill="#2e2e39"/>
<rect x="80" y="390" width="${Math.round(barW * pct)}" height="28" rx="14" fill="#f25c2a"/>
<text x="80" y="500" fill="#ffffff" font-family="Inter, Helvetica, Arial, sans-serif" font-size="36">Free, offline design tool. No account. No watermark.</text>
<text x="80" y="560" fill="#9a9aab" font-family="Inter, Helvetica, Arial, sans-serif" font-size="28">${summary.todo} not done yet, listed publicly · open source (MIT) · ${summary.date}</text>
</svg>
`;
writeFileSync(join(root, 'docs/scoreboard.svg'), card);

// README table.
const readmePath = join(root, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const table = [
  '<!-- scoreboard:start -->',
  `**${summary.verified} of ${summary.total} features verified** by browser tests · ${summary.todo} not done yet · [full scoreboard](SCOREBOARD.md)`,
  '',
  '| Area | Verified |',
  '| --- | --- |',
  ...areas.map((a) => `| ${a.name} | ${a.features.filter((f) => f.status === 'verified').length} / ${a.features.length} |`),
  '',
  `Not done yet: ${all.filter((f) => f.status !== 'verified').map((f) => f.title.toLowerCase()).join('; ') || 'nothing'}.`,
  '<!-- scoreboard:end -->',
].join('\n');
if (readme.includes('<!-- scoreboard:start -->')) {
  writeFileSync(readmePath, readme.replace(/<!-- scoreboard:start -->[\s\S]*<!-- scoreboard:end -->/, table));
}

console.log(`\n${summary.verified}/${summary.total} features verified, ${summary.failing} failing, ${summary.todo} not yet.`);
console.log(`${summary.e2ePassing}/${summary.e2eTests} browser tests, ${summary.unitPassing}/${summary.unitTests} unit tests.`);
for (const f of all.filter((x) => x.status === 'failing')) console.log(`FAILING ${f.id} ${f.title}`);
process.exitCode = summary.failing ? 1 : 0;
